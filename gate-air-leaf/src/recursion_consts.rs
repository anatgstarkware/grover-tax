//! PINNED recursion VERIFIER config — a SINGLE `RecursionConfig` for one operating point, so nothing
//! security-relevant (n_queries / pow_bits / blowup / fold_step / lifting / column shapes / roots) is
//! derived at prove or verify time. proving-utils turns it into the runtime form internally
//! (`build_recursion_precompute`). Regenerate for a different `k` with `scripts/regen_recursion_consts.sh
//! <k>` (runs `capture_all` + `scripts/gen_recursion_consts.py`).
//!
//! The pinned point is keyed by the public `(k, shots_per_shard)` — which fix `N` (`n_leaves`) and the
//! base-shard shape. The security params (`level1`/`fold` blocks, unpacker PCS) are k-INDEPENDENT; only
//! `leaf.root`, the `unpacker` root/columns/n_outputs, and `n_leaves` vary with `k`. main asserts the
//! run's `(k, shots, N)` match `CAPTURED_K`/`CAPTURED_SHOTS`/`CAPTURED_N` and panics (regenerate) otherwise.
//!
