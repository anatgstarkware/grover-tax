/// Fold arity `k`: each internal node verifies exactly this many children (`k`-to-1 fold). The
/// single source of truth for the arity (fold, unpacker preimage, in-circuit node hash). A level's
/// `len() % FOLD_ARITY` remainder is carried up unchanged.
pub const FOLD_ARITY: usize = 8;

/// Recursion (node-node / root) and leaf-wrap FRI blowup factor the pinned point was captured with.
/// Feeds the ~96-bit-secure `(pow_bits, n_queries)` table via `get_pcs_config`.
pub const RECURSION_LOG_BLOWUP: u32 = 3;

/// Gate count of the iadd256 benchmark circuit. Fixed to this circuit (NOT generalized to other
/// circuits); with `samples=9024` and the `2^26` GPU-resident row cap it sets `shots_per_shard`.
pub const N_GATES: usize = 2547;

/// Shots per base shard for fold repetitions `k`: `floor(2^26 / (k * N_GATES))` — the max shot count
/// whose trace fits the `2^26` GPU-resident row cap. `n_shards = ceil(samples / shots_per_shard)`.
pub fn shots_per_shard(k: usize) -> usize {
    (1usize << 26) / (k * N_GATES)
}

